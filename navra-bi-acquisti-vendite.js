        const source=lot?.id||w.id;
        const key=source+'|'+norm(category);
        const old=byGroup.get(key);
        const name=lot?(ld.name||'Lotto senza nome'):[d.brand,d.model].filter(Boolean).join(' ')||'Articolo senza nome';
