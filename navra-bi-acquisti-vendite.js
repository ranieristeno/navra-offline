  function periodStats(rows,year,key='amount') {
    const c=current(),historical=year<c.y;
    const end=historical?`${year}-12-31`:c.date;
    const from=`${year}-01-01`,prevFrom=`${year-1}-01-01`;
    const prevEnd=historical?`${year-1}-12-31`:ymd(year-1,c.m,Math.min(c.d,endOfMonth(year-1,c.m)));
    const ytd=rangeSum(rows,from,end,key),prior=rangeSum(rows,prevFrom,prevEnd,key);
    const month=historical?12:c.m, monthStart=ymd(year,month,1),monthEnd=historical?ymd(year,12,31):c.date;
    const previous=addMonth(year,month,-1);
    const previousEnd=historical?ymd(previous.y,previous.m,endOfMonth(previous.y,previous.m)):ymd(previous.y,previous.m,Math.min(c.d,endOfMonth(previous.y,previous.m)));
    return {historical,ytd,prior,from,end,month,monthValue:rangeSum(rows,monthStart,monthEnd,key),
      prevMonthValue:rangeSum(rows,ymd(previous.y,previous.m,1),previousEnd,key)};
  }
